const countriesByCode = new Map(FLAG_GUESS_COUNTRIES.map((country) => [country.code, country]))

export function findFlagGuessCountry(code: string) {
	return countriesByCode.get(code) ?? null
}

export function listFlagGuessCountries(difficulty: FlagGuessDifficulty) {
	return FLAG_GUESS_COUNTRIES.filter((country) => country.difficulty === difficulty)
}

export function getFlagUrl(code: string) {
	return `https://flagcdn.com/w640/${code}.png`
}

export function listFlagGuessOptions(): FlagGuessCountryOption[] {
	return FLAG_GUESS_COUNTRIES.map(({ code, name }) => ({ code, name })).sort((a, b) =>
		a.name.localeCompare(b.name, "pt-BR"),
	)
}
